"""ORM models of the database tables (the schema itself is created by the Alembic migrations)."""

import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.db.vector import Vector


class Base(DeclarativeBase):
    pass


class User(Base):
    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint("role in ('admin', 'user')", name="users_role_check"),
        CheckConstraint("language is null or language in ('it', 'en')", name="users_language_check"),
        Index("users_username_lower_key", func.lower(text("username")), unique=True),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    username: Mapped[str] = mapped_column(Text, nullable=False)
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("true"))
    language: Mapped[str | None] = mapped_column(Text, nullable=True)
    session_epoch: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("0"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class KnowledgeBase(Base):
    __tablename__ = "knowledge_bases"
    __table_args__ = (
        CheckConstraint("char_length(name) between 1 and 100", name="knowledge_bases_name_length_check"),
        CheckConstraint(
            "description is null or char_length(description) <= 500", name="knowledge_bases_description_length_check"
        ),
        Index("knowledge_bases_name_lower_key", func.lower(text("name")), unique=True),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    name: Mapped[str] = mapped_column(Text, nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class KbMember(Base):
    """A user assigned to a knowledge base; the rows go away with the KB or the user (ON DELETE CASCADE)."""

    __tablename__ = "kb_members"
    __table_args__ = (Index("kb_members_user_id_idx", "user_id"),)

    kb_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("knowledge_bases.id", ondelete="CASCADE"), primary_key=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )


class Document(Base):
    """A file uploaded to a knowledge base. The reason columns are both set exactly when the status is FAILED or
    UNSUPPORTED; a READY document has at least one chunk. The id is generated by the application because the
    original is stored under it before the row is inserted."""

    __tablename__ = "documents"
    __table_args__ = (
        CheckConstraint(
            "status in ('QUEUED', 'PROCESSING', 'READY', 'FAILED', 'UNSUPPORTED')", name="documents_status_check"
        ),
        CheckConstraint(
            "(status in ('FAILED', 'UNSUPPORTED')"
            " and coalesce(char_length(status_reason_code), 0) > 0"
            " and coalesce(char_length(status_reason_message), 0) > 0)"
            " or (status not in ('FAILED', 'UNSUPPORTED')"
            " and status_reason_code is null and status_reason_message is null)",
            name="documents_status_reason_check",
        ),
        CheckConstraint("status <> 'READY' or chunk_count > 0", name="documents_ready_chunks_check"),
        # The same content (SHA-256) is stored once per KB, in any status; it also serves the reads by kb_id.
        Index("documents_kb_id_checksum_key", "kb_id", "checksum", unique=True),
        # Target of the composite foreign key of the chunks (a chunk has the KB of its document).
        UniqueConstraint("id", "kb_id", name="documents_id_kb_id_key"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4, server_default=func.gen_random_uuid()
    )
    kb_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("knowledge_bases.id", ondelete="CASCADE"), nullable=False
    )
    filename: Mapped[str] = mapped_column(Text, nullable=False)
    format: Mapped[str] = mapped_column(Text, nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    checksum: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'QUEUED'"))
    status_reason_code: Mapped[str | None] = mapped_column(Text, nullable=True)
    status_reason_message: Mapped[str | None] = mapped_column(Text, nullable=True)
    # The profile the document was indexed with; set together with its chunks, null until then.
    profile_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("indexing_profiles.id"), nullable=True
    )
    chunk_count: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("0"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )


class IndexingProfile(Base):
    """Embedding model, dimensions, parser, chunker parameters and BM25 configuration that produced a set of chunks.
    One row per configuration; documents and chunks keep the profile they were created with."""

    __tablename__ = "indexing_profiles"
    __table_args__ = (
        CheckConstraint("dimensions between 1 and 2000", name="indexing_profiles_dimensions_check"),
        UniqueConstraint(
            "embedding_model",
            "dimensions",
            "parser",
            "chunker",
            "bm25_config",
            name="indexing_profiles_configuration_key",
        ),
        UniqueConstraint("id", "dimensions", name="indexing_profiles_id_dimensions_key"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4, server_default=func.gen_random_uuid()
    )
    embedding_model: Mapped[str] = mapped_column(Text, nullable=False)
    dimensions: Mapped[int] = mapped_column(Integer, nullable=False)
    parser: Mapped[str] = mapped_column(Text, nullable=False)
    chunker: Mapped[dict[str, int]] = mapped_column(JSONB, nullable=False)
    bm25_config: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class Chunk(Base):
    """A piece of a document with its vector. The database keeps it consistent: the vector has `dimensions` components
    (CHECK), `(profile_id, dimensions)` is a row of `indexing_profiles` and `(document_id, kb_id)` a row of `documents`
    (composite foreign keys: the chunk has the KB of its document, and goes away with it). The
    BM25 index `chunks_bm25` and the HNSW index of each profile exist only in the database (migration 0004 and
    `ensure_profile`)."""

    __tablename__ = "chunks"
    __table_args__ = (
        ForeignKeyConstraint(
            ["document_id", "kb_id"],
            ["documents.id", "documents.kb_id"],
            ondelete="CASCADE",
            name="chunks_document_kb_fkey",
        ),
        ForeignKeyConstraint(
            ["profile_id", "dimensions"],
            ["indexing_profiles.id", "indexing_profiles.dimensions"],
            name="chunks_profile_fkey",
        ),
        CheckConstraint("position >= 0", name="chunks_position_check"),
        CheckConstraint("word_count >= 0", name="chunks_word_count_check"),
        CheckConstraint("vector_dims(embedding) = dimensions", name="chunks_embedding_dimensions_check"),
        UniqueConstraint("document_id", "position", name="chunks_document_position_key"),
        Index("chunks_kb_id_idx", "kb_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4, server_default=func.gen_random_uuid()
    )
    kb_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    document_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    profile_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    dimensions: Mapped[int] = mapped_column(Integer, nullable=False)
    position: Mapped[int] = mapped_column(Integer, nullable=False)
    section_title: Mapped[str | None] = mapped_column(Text, nullable=True)
    page_start: Mapped[int | None] = mapped_column(Integer, nullable=True)
    page_end: Mapped[int | None] = mapped_column(Integer, nullable=True)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    word_count: Mapped[int] = mapped_column(Integer, nullable=False)
    embedding: Mapped[list[float]] = mapped_column(Vector(), nullable=False)
